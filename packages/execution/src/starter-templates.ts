export type ProjectType = "nextjs" | "java" | "unknown";

/**
 * Detect the project type from a blueprint's tech stack entries.
 */
export function detectProjectType(techStackNames: string[]): ProjectType {
  const names = techStackNames.map((n) => n.toLowerCase());
  if (names.some((n) => n.includes("next") || n.includes("react"))) {
    return "nextjs";
  }
  if (
    names.some(
      (n) => n.includes("spring") || n.includes("java") || n.includes("maven"),
    )
  ) {
    return "java";
  }
  return "unknown";
}

/**
 * Returns the starter template for the given project type.
 * Returns an empty record for unknown project types.
 */
export function getStarterTemplate(type: ProjectType): StarterTemplate {
  if (type === "nextjs") return nextjsStarterTemplate;
  if (type === "java") return javaStarterTemplate;
  return {};
}
