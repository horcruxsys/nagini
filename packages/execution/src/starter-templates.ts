/**
 * "Golden Starter" templates give the Coder Agent a safe baseline for common
 * project configurations so it doesn't have to reinvent boilerplate every run.
 *
 * Each template is a map of `filePath → fileContent`.
 * The File Orchestrator injects these at the start of a session before calling
 * the Coder Agent for domain-specific files.
 */

export type StarterTemplate = Record<string, string>;

